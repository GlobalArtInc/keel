    #[test]
    fn a_changed_parameter_schema_fails_the_check_without_rewriting_the_document() {
        let temporary = tempfile::tempdir().unwrap();
        let dump = dump(temporary.path(), &fixture());
        let out = temporary.path().join("contracts").join("openapi.json");
        let written = run(&dump, &out, false).unwrap();
        assert_eq!(written.verdict, Verdict::Written);
        assert_eq!(written.functions, 4);
        assert_eq!(
            written.to_string(),
            format!("4 functions written to {}", out.display())
        );
        let text = fs::read_to_string(&out).unwrap();
        assert!(text.ends_with('\n'));
        assert_eq!(run(&dump, &out, true).unwrap().verdict, Verdict::Current);

        let path = dump
            .join("admin")
            .join(FUNCTIONS_DIR)
            .join("note.edit.json");
        let mut descriptor: Value =
            serde_json::from_str(&fs::read_to_string(&path).unwrap()).unwrap();
        descriptor["params"]["properties"]["title"]["maxLength"] = json!(120);
        write(&path, &descriptor);
        let outcome = run(&dump, &out, true).unwrap();
        assert!(!outcome.current());
        let Verdict::Stale(diff) = &outcome.verdict else {
            panic!("expected a stale document, got {:?}", outcome.verdict);
        };
        assert!(removed_line(diff, "\"maxLength\": 200"), "{diff}");
        assert!(added_line(diff, "\"maxLength\": 120"), "{diff}");
        assert!(diff.starts_with(&format!("--- {COMMITTED_LABEL}/{}\n", out.display())));
        assert!(diff.contains(&format!("+++ {GENERATED_LABEL}/{}\n", out.display())));
        assert_eq!(
            fs::read_to_string(&out).unwrap(),
            text,
            "check rewrites nothing"
        );
        let report = outcome.to_string();
        assert!(report.starts_with(diff));
        assert!(report.ends_with(&format!(
            "{} would change; run `keel-dev openapi --dump {} --out {}` and commit the result",
            out.display(),
            dump.display(),
            out.display()
        )));

        fs::remove_file(&out).unwrap();
        let Verdict::Stale(diff) = run(&dump, &out, true).unwrap().verdict else {
            panic!("a missing document is stale");
        };
        assert!(diff.starts_with("--- /dev/null\n"));
        assert!(!out.exists());
    }

