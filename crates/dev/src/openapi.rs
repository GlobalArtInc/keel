#[derive(Debug, thiserror::Error)]
pub enum Error {
    #[error("{}: {source}", path.display())]
    Io { path: PathBuf, source: io::Error },
    #[error("{}: {source}", path.display())]
    Json {
        path: PathBuf,
        source: serde_json::Error,
    },
    #[error("{}: expected a boot payload with keel.version", path.display())]
    Version { path: PathBuf },
    #[error("{scope} refers to {reference}, which keel-types does not define")]
    UnknownShared { scope: String, reference: String },
    #[error("{scope} refers to {reference}, which its $defs do not hold")]
    Dangling { scope: String, reference: String },
    #[error("the definition {name} of {a} and {b} differ once their references are rewritten")]
    Collision { name: String, a: String, b: String },
    #[error("keel-types describes no envelope branch with ok: {0}")]
    Envelope(bool),
    #[error(transparent)]
    Types(#[from] types::Error),
}

#[derive(Debug, PartialEq, Eq)]
pub enum Verdict {
    Written,
    Current,
    Stale(String),
}

#[derive(Debug)]
pub struct Outcome {
    pub dump: PathBuf,
    pub path: PathBuf,
    pub functions: usize,
    pub verdict: Verdict,
}

impl Outcome {
    pub fn current(&self) -> bool {
        !matches!(self.verdict, Verdict::Stale(_))
    }
}

impl fmt::Display for Outcome {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match &self.verdict {
            Verdict::Written => write!(
                f,
                "{} functions written to {}",
                self.functions,
                self.path.display()
            ),
            Verdict::Current => write!(
                f,
                "{} functions up to date in {}",
                self.functions,
                self.path.display()
            ),
            Verdict::Stale(diff) => write!(
                f,
                "{diff}{} would change; run `keel-dev openapi --dump {} --out {}` and commit the result",
                self.path.display(),
                self.dump.display(),
                self.path.display()
            ),
        }
    }
}

#[derive(Debug)]
pub struct Document {
    pub value: Value,
    pub functions: usize,
}

struct Scope {
    name: String,
    definitions: Map<String, Value>,
}

struct Part {
    schema: Value,
    scope: Scope,
}

struct Function {
    descriptor: Descriptor,
    params: Part,
    result: Part,
}

struct Found {
    definition: Value,
    scope: String,
}

struct Variant {
    definition: Value,
    component: String,
}

struct Hoist {
    shared: BTreeMap<String, Value>,
    variants: BTreeMap<String, Vec<Variant>>,
}

impl Hoist {
    fn new(
        definitions: &Map<String, Value>,
        shared: BTreeMap<String, Value>,
        found: BTreeMap<String, Vec<Found>>,
    ) -> Self {
        let variants = found
            .into_iter()
            .map(|(name, found)| {
                let shared_definition = shared.get(&name).and_then(|_| definitions.get(&name));
                let distinct = found
                    .iter()
                    .filter(|found| Some(&found.definition) != shared_definition)
                    .count()
                    + usize::from(shared_definition.is_some());
                let variants = found
                    .into_iter()
                    .map(|found| Variant {
                        component: if distinct == 1 || Some(&found.definition) == shared_definition
                        {
                            name.clone()
                        } else {
                            format!("{}.{name}", found.scope)
                        },
                        definition: found.definition,
                    })
                    .collect();
                (name, variants)
            })
            .collect();
        Self { shared, variants }
    }

    fn component_of(&self, scope: &Scope, name: &str) -> Result<String, Error> {
        let dangling = || Error::Dangling {
            scope: scope.name.clone(),
            reference: format!("{DEFINITIONS}{name}"),
        };
        let definition = scope.definitions.get(name).ok_or_else(dangling)?;
        self.variants
            .get(name)
            .and_then(|variants| {
                variants
                    .iter()
                    .find(|variant| variant.definition == *definition)
            })
            .map(|variant| variant.component.clone())
            .ok_or_else(dangling)
    }

    fn rewrite(&self, value: &mut Value, scope: &Scope) -> Result<(), Error> {
        match value {
            Value::Object(map) => {
                if let Some(Value::String(reference)) = map.get_mut("$ref") {
                    if let Some(name) = reference.strip_prefix(SHARED_SCHEME) {
                        if !self.shared.contains_key(name) {
                            return Err(Error::UnknownShared {
                                scope: scope.name.clone(),
                                reference: reference.clone(),
                            });
                        }
                        *reference = format!("{COMPONENTS}{name}");
                    } else if let Some(name) = reference.strip_prefix(DEFINITIONS) {
                        let component = self.component_of(scope, name)?;
                        *reference = format!("{COMPONENTS}{component}");
                    }
                }
                for member in map.values_mut() {
                    self.rewrite(member, scope)?;
                }
            }
            Value::Array(items) => {
                for item in items {
                    self.rewrite(item, scope)?;
                }
            }
            _ => {}
        }
        Ok(())
    }
}

fn references(value: &Value, prefix: &str, into: &mut BTreeSet<String>) {
    match value {
        Value::Object(map) => {
            if let Some(name) = map
                .get("$ref")
                .and_then(Value::as_str)
                .and_then(|reference| reference.strip_prefix(prefix))
            {
                into.insert(name.to_owned());
            }
            for member in map.values() {
                references(member, prefix, into);
            }
        }
        Value::Array(items) => {
            for item in items {
                references(item, prefix, into);
            }
        }
        _ => {}
    }
}

fn rewrite_shared(value: &mut Value) {
    match value {
        Value::Object(map) => {
            if let Some(Value::String(reference)) = map.get_mut("$ref")
                && let Some(name) = reference.strip_prefix(DEFINITIONS)
            {
                *reference = format!("{COMPONENTS}{name}");
            }
            for member in map.values_mut() {
                rewrite_shared(member);
            }
        }
        Value::Array(items) => {
            for item in items {
                rewrite_shared(item);
            }
        }
        _ => {}
    }
}

fn closure(definitions: &Map<String, Value>, roots: BTreeSet<String>) -> BTreeMap<String, Value> {
    let mut included = BTreeMap::new();
    let mut pending: Vec<String> = roots.into_iter().collect();
    while let Some(name) = pending.pop() {
        if included.contains_key(&name) {
            continue;
        }
        let Some(definition) = definitions.get(&name) else {
            continue;
        };
        let mut referenced = BTreeSet::new();
        references(definition, DEFINITIONS, &mut referenced);
        pending.extend(referenced);
        let mut definition = definition.clone();
        rewrite_shared(&mut definition);
        included.insert(name, definition);
    }
    included
}

fn envelope_branch(definitions: &Map<String, Value>, ok: bool) -> Result<Value, Error> {
    definitions
        .get(ENVELOPE)
        .and_then(|envelope| envelope["oneOf"].as_array())
        .and_then(|branches| {
            branches
                .iter()
                .find(|branch| branch["properties"]["ok"]["const"] == json!(ok))
        })
        .cloned()
        .map(|mut branch| {
            rewrite_shared(&mut branch);
            branch
        })
        .ok_or(Error::Envelope(ok))
}

fn refused() -> String {
    let mut by_status: BTreeMap<u16, Vec<&str>> = BTreeMap::new();
    for code in ErrorCode::ALL {
        by_status
            .entry(code.status())
            .or_default()
            .push(code.as_str());
    }
    let statuses: Vec<String> = by_status
        .iter()
        .map(|(status, codes)| format!("{status} {}", codes.join(", ")))
        .collect();
    format!("{REFUSED}: {}.", statuses.join("; "))
}

fn read_json(path: &Path) -> Result<Value, Error> {
    let text = fs::read_to_string(path).map_err(io(path))?;
    serde_json::from_str(&text).map_err(|source| Error::Json {
        path: path.to_path_buf(),
        source,
    })
}

fn io(path: &Path) -> impl FnOnce(io::Error) -> Error {
    let path = path.to_path_buf();
    move |source| Error::Io { path, source }
}

fn version_of(path: &Path) -> Result<String, Error> {
    read_json(path)?["keel"]["version"]
        .as_str()
        .map(str::to_owned)
        .ok_or_else(|| Error::Version {
            path: path.to_path_buf(),
        })
}

fn descriptors_of(dir: &Path) -> Result<Vec<Descriptor>, Error> {
    let mut descriptors = Vec::new();
    for entry in fs::read_dir(dir).map_err(io(dir))? {
        let path = entry.map_err(io(dir))?.path();
        if path.extension().is_none_or(|extension| extension != "json") {
            continue;
        }
        let descriptor: Descriptor =
            serde_json::from_value(read_json(&path)?).map_err(|source| Error::Json {
                path: path.clone(),
                source,
            })?;
        descriptors.push(descriptor);
    }
    descriptors.sort_by(|a, b| a.name.cmp(&b.name));
    Ok(descriptors)
}

fn shared_definitions() -> Result<Map<String, Value>, Error> {
    let mut document = types::document()?.schema;
    Ok(match document["$defs"].take() {
        Value::Object(definitions) => definitions,
        _ => Map::new(),
    })
}

fn part(
    func: &str,
    part: &str,
    mut schema: Value,
    roots: &mut BTreeSet<String>,
    found: &mut BTreeMap<String, Vec<Found>>,
) -> Part {
    references(&schema, SHARED_SCHEME, roots);
    let definitions = match schema.as_object_mut().and_then(|map| map.remove("$defs")) {
        Some(Value::Object(definitions)) => definitions,
        _ => Map::new(),
    };
    let scope = Scope {
        name: format!("{func}.{part}"),
        definitions,
    };
    for (name, definition) in &scope.definitions {
        let known = found.entry(name.clone()).or_default();
        if !known.iter().any(|found| found.definition == *definition) {
            known.push(Found {
                definition: definition.clone(),
                scope: scope.name.clone(),
            });
        }
    }
    Part { schema, scope }
}

fn hoist(
    definitions: &Map<String, Value>,
    descriptors: Vec<Descriptor>,
) -> Result<(Vec<Function>, BTreeMap<String, Value>), Error> {
    let mut roots: BTreeSet<String> = [META, CALL_ERROR].into_iter().map(str::to_owned).collect();
    let mut found = BTreeMap::new();
    let mut functions = Vec::with_capacity(descriptors.len());
    for descriptor in descriptors {
        let params = part(
            &descriptor.name,
            PARAMS,
            descriptor.params.as_value().clone(),
            &mut roots,
            &mut found,
        );
        let result = part(
            &descriptor.name,
            RESULT,
            descriptor.result.as_value().clone(),
            &mut roots,
            &mut found,
        );
        functions.push(Function {
            descriptor,
            params,
            result,
        });
    }
    let hoist = Hoist::new(definitions, closure(definitions, roots), found);
    let mut components: BTreeMap<String, (Value, String)> = hoist
        .shared
        .iter()
        .map(|(name, definition)| (name.clone(), (definition.clone(), TITLE.to_owned())))
        .collect();
    for function in &mut functions {
        for part in [&mut function.params, &mut function.result] {
            hoist.rewrite(&mut part.schema, &part.scope)?;
            for (name, definition) in &part.scope.definitions {
                let component = hoist.component_of(&part.scope, name)?;
                let mut definition = definition.clone();
                hoist.rewrite(&mut definition, &part.scope)?;
                match components.get(&component) {
                    Some((existing, _)) if *existing == definition => {}
                    Some((_, owner)) => {
                        return Err(Error::Collision {
                            name: component,
                            a: owner.clone(),
                            b: part.scope.name.clone(),
                        });
                    }
                    None => {
                        components.insert(component, (definition, part.scope.name.clone()));
                    }
                }
            }
        }
    }
    let schemas = components
        .into_iter()
        .map(|(name, (definition, _))| (name, definition))
        .collect();
    Ok((functions, schemas))
}

fn operation(function: &Function, success: &Value) -> Value {
    let descriptor = &function.descriptor;
    let mut response = success.clone();
    response["properties"]["data"] = function.result.schema.clone();
    let required = function.params.schema["required"]
        .as_array()
        .is_some_and(|required| !required.is_empty());
    let mut operation = json!({
        "operationId": descriptor.name,
        "tags": [descriptor.module],
        "x-keel": {
            "kind": descriptor.kind,
            "mode": descriptor.mode,
            "access": descriptor.access
        },
        "requestBody": {
            "required": required,
            "content": { JSON: { "schema": function.params.schema } }
        },
        "responses": {
            "200": {
                "description": COMPLETED,
                "content": { JSON: { "schema": response } }
            },
            "default": { "$ref": format!("#/components/responses/{ERROR_RESPONSE}") }
        }
    });
    if descriptor.access.level == Level::Guest
        && let Some(map) = operation.as_object_mut()
    {
        map.insert("security".to_owned(), json!([]));
    }
    operation
}

pub fn raw_route(descriptor: &Descriptor) -> String {
    let name = descriptor
        .name
        .strip_prefix(descriptor.module.as_str())
        .and_then(|rest| rest.strip_prefix('.'))
        .unwrap_or(descriptor.name.as_str());
    format!("{RAW_PREFIX}/{}/{name}", descriptor.module)
}

fn download(function: &Function) -> Value {
    let descriptor = &function.descriptor;
    let common = json!({
        "tags": [descriptor.module],
        "x-keel": {
            "kind": descriptor.kind,
            "mode": descriptor.mode,
            "access": descriptor.access,
            "result": function.result.schema
        },
        "responses": {
            "200": {
                "description": STREAMED,
                "content": { BINARY: { "schema": { "type": "string", "format": "binary" } } }
            },
            "default": { "$ref": format!("#/components/responses/{ERROR_RESPONSE}") }
        }
    });
    let mut get = common.clone();
    get["operationId"] = json!(format!("{}.get", descriptor.name));
    get["parameters"] = json!([{
        "name": QUERY_PARAMS,
        "in": "query",
        "required": false,
        "description": QUERY_DESCRIPTION,
        "content": { JSON: { "schema": function.params.schema } }
    }]);
    let mut post = common;
    post["operationId"] = json!(descriptor.name);
    post["requestBody"] = json!({
        "required": function.params.schema["required"]
            .as_array()
            .is_some_and(|required| !required.is_empty()),
        "content": { JSON: { "schema": function.params.schema } }
    });
    json!({ "get": get, "post": post })
}

pub fn document(dump: &Path) -> Result<Document, Error> {
    let level = dump.join(DOCUMENT_LEVEL.as_str());
    let version = version_of(&level.join(BOOT_FILE))?;
    let descriptors = descriptors_of(&level.join(FUNCTIONS_DIR))?;
    let definitions = shared_definitions()?;
    let success = envelope_branch(&definitions, true)?;
    let failure = envelope_branch(&definitions, false)?;
    let (functions, schemas) = hoist(&definitions, descriptors)?;
    let mut paths = Map::new();
    for function in &functions {
        if function.descriptor.kind == Kind::Download {
            paths.insert(raw_route(&function.descriptor), download(function));
            continue;
        }
        paths.insert(
            format!("{API_PREFIX}/call/{}", function.descriptor.name),
            json!({ "post": operation(function, &success) }),
        );
    }
    let value = json!({
        "openapi": OPENAPI_VERSION,
        "info": { "title": TITLE, "version": version, "description": DESCRIPTION },
        "security": [{ TOKEN_SCHEME: [] }, { SESSION_SCHEME: [] }],
        "paths": paths,
        "components": {
            "schemas": schemas,
            "responses": {
                ERROR_RESPONSE: {
                    "description": refused(),
                    "content": { JSON: { "schema": failure } }
                }
            },
            "securitySchemes": {
                TOKEN_SCHEME: { "type": "http", "scheme": "bearer" },
                SESSION_SCHEME: { "type": "apiKey", "in": "cookie", "name": SESSION_COOKIE }
            }
        }
    });
    Ok(Document {
        value,
        functions: functions.len(),
    })
}

pub fn render(dump: &Path) -> Result<(String, usize), Error> {
    let document = document(dump)?;
    let mut text = serde_json::to_string_pretty(&document.value).map_err(|source| Error::Json {
        path: dump.to_path_buf(),
        source,
    })?;
    text.push('\n');
    Ok((text, document.functions))
}

pub fn run(dump: &Path, out: &Path, check: bool) -> Result<Outcome, Error> {
    let (text, functions) = render(dump)?;
    let verdict = if check {
        let committed = match fs::read_to_string(out) {
            Ok(existing) => Some(existing),
            Err(error) if error.kind() == io::ErrorKind::NotFound => None,
            Err(source) => return Err(io(out)(source)),
        };
        if committed.as_deref() == Some(text.as_str()) {
            Verdict::Current
        } else {
            Verdict::Stale(unified(
                &out.display().to_string(),
                committed.as_deref(),
                Some(&text),
                COMMITTED_LABEL,
                GENERATED_LABEL,
            ))
        }
    } else {
        if let Some(parent) = out.parent().filter(|parent| !parent.as_os_str().is_empty()) {
            fs::create_dir_all(parent).map_err(io(parent))?;
        }
        fs::write(out, &text).map_err(io(out))?;
        Verdict::Written
    };
    Ok(Outcome {
        dump: dump.to_path_buf(),
        path: out.to_path_buf(),
        functions,
        verdict,
    })
}

