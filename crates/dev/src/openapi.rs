    #[test]
    fn an_unknown_shared_reference_a_dangling_definition_a_collision_and_a_missing_dump_are_refused()
     {
        let temporary = tempfile::tempdir().unwrap();
        let unknown = dump(
            &temporary.path().join("unknown"),
            &[descriptor(
                "x.get",
                "user",
                json!({ "$ref": "keel://Nothing" }),
                json!({ "type": "object" }),
            )],
        );
        let error = document(&unknown).unwrap_err();
        assert!(
            matches!(&error, Error::UnknownShared { scope, reference } if scope == "x.get.params" && reference == "keel://Nothing"),
            "{error}"
        );

        let dangling = dump(
            &temporary.path().join("dangling"),
            &[descriptor(
                "x.get",
                "user",
                json!({ "type": "object" }),
                json!({ "type": "object", "properties": { "id": { "$ref": "#/$defs/Id" } } }),
            )],
        );
        let error = document(&dangling).unwrap_err();
        assert!(
            matches!(&error, Error::Dangling { scope, reference } if scope == "x.get.result" && reference == "#/$defs/Id"),
            "{error}"
        );

        let collision = dump(
            &temporary.path().join("collision"),
            &[
                descriptor(
                    "a.get",
                    "user",
                    json!({ "type": "object" }),
                    json!({ "type": "object", "properties": { "row": { "$ref": "#/$defs/Row" } }, "$defs": { "Row": note_definition(), "Id": { "type": "string" } } }),
                ),
                descriptor(
                    "b.get",
                    "user",
                    json!({ "type": "object" }),
                    json!({ "type": "object", "properties": { "row": { "$ref": "#/$defs/Row" } }, "$defs": { "Row": note_definition(), "Id": { "type": "integer" } } }),
                ),
            ],
        );
        let error = document(&collision).unwrap_err();
        assert!(
            matches!(&error, Error::Collision { name, a, b } if name == "Row" && a == "a.get.result" && b == "b.get.result"),
            "{error}"
        );

        let error = document(&temporary.path().join("nowhere")).unwrap_err();
        assert!(matches!(error, Error::Io { .. }), "{error}");

        let unversioned = dump(&temporary.path().join("unversioned"), &[]);
        write(
            &unversioned.join("admin").join(BOOT_FILE),
            &json!({ "views": [] }),
        );
        let error = document(&unversioned).unwrap_err();
        assert!(matches!(error, Error::Version { .. }), "{error}");
    }
